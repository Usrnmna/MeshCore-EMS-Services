"""Bind local installer bytes to the exact maintained build inputs.

These records establish local source freshness, not publisher authentication.
They are generated by the builder and are required when assembling desktop kits.
"""

import hashlib
import json
from pathlib import Path


def file_hash(path):
    """Hash large installer and reference files without loading them into memory."""
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def source_hashes(sources, root):
    """Return a stable, complete inventory relative to the checked-out project."""
    root = Path(root).resolve()
    return {Path(path).resolve().relative_to(root).as_posix(): file_hash(path)
            for path in sorted(set(map(Path, sources)))}


def write_provenance(artifact, kind, sources, *, root, target, dataset=None):
    """Record source and artifact hashes only after successful compilation."""
    artifact = Path(artifact)
    record = {"schema": 1, "kind": kind, "target": target, "dataset": dataset,
              "artifact": artifact.name, "artifact_sha256": file_hash(artifact),
              "source_sha256": source_hashes(sources, root)}
    if kind == "service":
        record["capabilities"] = ["staged-startup-v1", "settings-v2", "operation-lock-v1"]
    elif kind == "dataset":
        record["capabilities"] = ["retain-data-v1", "maintenance-lock-v1", "dataset-lock-recovery-v1"]
    path = artifact.with_name(artifact.name + ".provenance.json")
    path.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def verify_provenance(artifact, kind, sources, *, root, target, dataset=None):
    """Reject missing provenance, modified binaries and changed/additional inputs."""
    artifact = Path(artifact)
    path = artifact.with_name(artifact.name + ".provenance.json")
    if not path.is_file():
        raise ValueError(f"Rebuild {artifact.name}: current build provenance is missing")
    record = json.loads(path.read_text(encoding="utf-8"))
    identity = (record.get("schema"), record.get("kind"), record.get("target"), record.get("dataset"))
    if identity != (1, kind, target, dataset):
        raise ValueError("Installer provenance kind, target or dataset does not match")
    if record.get("artifact") != artifact.name or record.get("artifact_sha256") != file_hash(artifact):
        raise ValueError("Installer artifact bytes no longer match build provenance")
    if record.get("source_sha256") != source_hashes(sources, root):
        raise ValueError(f"Rebuild {artifact.name}: maintained source/build inputs changed")
    return record
